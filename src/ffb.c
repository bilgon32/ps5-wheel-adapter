#define LG_COMMAND_MASK 0x0fu
#define LG_SLOT_MASK 0xf0u
#define LG_DOWNLOAD 0x00u
#define LG_DOWNLOAD_AND_PLAY 0x01u
#define LG_REFRESH 0x0cu
#define LG_CONSTANT_FORCE 0x00u
#define LG_VARIABLE_FORCE 0x08u

